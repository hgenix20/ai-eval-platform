"""Build the groundedness suite's fixtures and cases from the SignalNodus
golden set and the SEC documents it cites.

For every golden case that carries at least one `must_contain` anchor, this
fetches the primary document from sec.gov (cached under `.cache/edgar`),
converts it to paragraphs, cuts out the item's section, locates each anchor
inside that section, and writes:

- `<out>/fixtures/<accession>-<item>.json`, the windowed paragraphs the
  retriever server serves, with each anchor's paragraph id and sentence
- `<out>/<golden id>-a<n>.yaml`, one case per anchor

A case whose anchors are not all inside the located section is skipped and
printed with the reason, so the yield is visible in the build output and can
be recorded in the suite README.

    python scripts/build_edgar_fixtures.py \
        --golden suites/groundedness/golden.json --out suites/groundedness

Network use: one GET per distinct document, 0.5 s apart, 60 s timeout, with
the User-Agent sec.gov asks automated readers to send. A 403 or 429 backs
off 10 s and retries up to three times before the case is skipped. Nothing
is fetched again once it is in the cache, so a rebuild is offline.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
import textwrap
import time
from pathlib import Path
from typing import Any

import httpx

from eval_platform.graders.hhem import split_sentences

USER_AGENT = "ai-eval-platform research hgenix@agentmail.to"
REQUEST_TIMEOUT = 60.0
REQUEST_SPACING_S = 0.5
BACKOFF_S = 10.0
MAX_ATTEMPTS = 3
RATE_LIMIT_CODES = (403, 429)
WINDOW_PARAGRAPHS = 40
# A heading is a short paragraph that starts with the item number. The cap
# keeps a body sentence that happens to mention "Item 1A" from being read as
# the start of the section.
MAX_HEADING_CHARS = 200
# The item that follows each item we build from, so the section ends where
# the next one starts.
NEXT_ITEM = {"1A": "1B", "2": "3", "7": "7A"}
ITEM_TITLES = {
    "1A": "Risk Factors",
    "2": "Management's Discussion and Analysis",
    "7": "Management's Discussion and Analysis",
}
_BLOCK_END = re.compile(r"</(?:p|div|li|tr|td|th|table|h[1-6])>|<br\s*/?>", re.IGNORECASE)
_SCRIPT = re.compile(r"<(script|style)\b.*?</\1>", re.IGNORECASE | re.DOTALL)
_TAG = re.compile(r"<[^>]+>")
_ANY_ITEM_HEADING = re.compile(r"^item\s*\d+[a-z]?\.?", re.IGNORECASE)
CASE_HEADER = """\
# Generated by scripts/build_edgar_fixtures.py from the SignalNodus golden set
# (suites/groundedness/golden.json). The question is a template; the graded
# facts are the anchor sentence and whether every quoted span exists in what
# the retriever returned.
"""


class SkipCaseError(Exception):
    """This golden case cannot produce a fixture; the message says why."""


def to_paragraphs(raw_html: str) -> list[str]:
    """One string per HTML block element, whitespace-normalized, empties
    dropped.

    Block ends (`</p>`, `</div>`, `</li>`, `</tr>`, table cells, headings,
    `<br>`) become newlines, remaining tags become spaces, entities are
    unescaped after the tags are gone so an escaped `&lt;p&gt;` in the text
    cannot fake a block boundary, and each line's whitespace runs (including
    non-breaking spaces) collapse to one space.
    """
    text = _SCRIPT.sub(" ", raw_html)
    text = _BLOCK_END.sub("\n", text)
    text = _TAG.sub(" ", text)
    text = html.unescape(text)
    out: list[str] = []
    for line in text.split("\n"):
        collapsed = " ".join(line.replace("\xa0", " ").split())
        if collapsed:
            out.append(collapsed)
    return out


def _heading_indices(paragraphs: list[str], item: str) -> list[int]:
    """Indices of the short paragraphs that open with `Item <item>`.

    The item number is matched to its end, so `Item 7` does not match the
    `Item 7A.` heading that follows it, and `Item 1` never matches `Item 1A`.
    """
    pattern = re.compile(rf"^item\s*{re.escape(item)}(?![0-9a-z])\.?", re.IGNORECASE)
    return [
        i
        for i, p in enumerate(paragraphs)
        if len(p) <= MAX_HEADING_CHARS and pattern.match(p) is not None
    ]


def _is_titled(paragraph: str, item: str) -> bool:
    """Whether a heading carries the item's title and not only its number.
    A bare `Item 1A` is a table-of-contents line or the running header a
    filer repeats on every page; `Item 1A. Risk Factors` opens the section."""
    rest = re.sub(rf"^item\s*{re.escape(item)}[.:\s-]*", "", paragraph, flags=re.IGNORECASE)
    return sum(ch.isalpha() for ch in rest) >= 4


def _slice_end(paragraphs: list[str], item: str, start: int) -> int:
    """Where the section opened at `start` ends: the next item's heading,
    else the next `Item <number>` heading for any other item, else the end of
    the document. Headings for the item itself are never an end, since a
    filer repeats them as page headers and as `(Continued)` lines."""
    following = NEXT_ITEM.get(item)
    ends = [i for i in _heading_indices(paragraphs, following) if i > start] if following else []
    if ends:
        return ends[0]
    own = set(_heading_indices(paragraphs, item))
    generic = [
        i
        for i, p in enumerate(paragraphs)
        if i > start
        and i not in own
        and len(p) <= MAX_HEADING_CHARS
        and _ANY_ITEM_HEADING.match(p) is not None
    ]
    return generic[0] if generic else len(paragraphs)


def section_bounds(paragraphs: list[str], item: str, phrases: list[str]) -> tuple[int, int]:
    """The half-open paragraph range holding one item's section.

    A document names its items several times: once in the table of contents,
    once where the section starts, and often once per page as a running
    header. Titled headings are tried first, in document order, and the
    first one whose slice holds every anchor phrase wins; bare headings are
    the fallback for a filer who never repeats the title. Requiring the
    anchors decides between a table-of-contents line and the section it
    points at without guessing where the front matter ends.

    Raises SkipCaseError when the item has no heading, or when no heading opens a
    slice holding every anchor.
    """
    starts = _heading_indices(paragraphs, item)
    if not starts:
        raise SkipCaseError(f"no heading for item {item}")
    titled = [i for i in starts if _is_titled(paragraphs[i], item)]
    lowered = [p.lower() for p in phrases]
    for candidates in (titled, starts):
        for start in candidates:
            end = _slice_end(paragraphs, item, start)
            section = [p.lower() for p in paragraphs[start:end]]
            if all(any(phrase in p for p in section) for phrase in lowered):
                return start, end
    raise SkipCaseError(f"no item {item} heading opens a section holding every anchor")


def anchor_sentence(paragraph: str, phrase: str) -> str:
    """The shortest run of consecutive sentences of `paragraph` that holds
    `phrase`, in the paragraph's own casing.

    Sentences come from `split_sentences`, which drops fragments shorter
    than 15 characters; when no run of them covers the phrase (the phrase
    sits in a dropped fragment, or the paragraph has no sentence break at
    all), the whole paragraph is the sentence. Always returns a substring of
    `paragraph`, so a fixture's anchor can be located in its own text.
    """
    needle = phrase.lower()
    sentences = split_sentences(paragraph)
    spans: list[tuple[int, int]] = []
    cursor = 0
    for s in sentences:
        begin = paragraph.find(s, cursor)
        if begin < 0:
            continue
        spans.append((begin, begin + len(s)))
        cursor = begin + len(s)
    best: tuple[int, int] | None = None
    for i, (begin, _) in enumerate(spans):
        for _, end in spans[i:]:
            if needle in paragraph[begin:end].lower():
                if best is None or end - begin < best[1] - best[0]:
                    best = (begin, end)
                break
    return paragraph[best[0] : best[1]] if best else paragraph


def _find_anchor(section: list[str], phrase: str) -> dict[str, Any]:
    """The first section paragraph containing `phrase` (case-insensitively),
    as a fixture anchor with its section-relative index. Raises SkipCaseError when
    the phrase is not in the section."""
    needle = phrase.lower()
    for offset, text in enumerate(section):
        if needle in text.lower():
            sentence = anchor_sentence(text, phrase)
            begin = sentence.lower().find(needle)
            return {
                "phrase": phrase,
                "offset": offset,
                "sentence": sentence,
                "cased_phrase": sentence[begin : begin + len(phrase)],
            }
    raise SkipCaseError(f"anchor not in the located section: {phrase!r}")


def window_ids(offsets: list[int], size: int, window: int) -> list[int]:
    """Every paragraph index within `window` of any anchor offset, clipped to
    [0, size) and de-duplicated, so overlapping windows merge."""
    keep: set[int] = set()
    for offset in offsets:
        keep.update(range(max(0, offset - window), min(size, offset + window + 1)))
    return sorted(keep)


def build_fixture(golden: dict[str, Any], raw_html: str, window: int) -> dict[str, Any]:
    """The fixture for one golden case, or SkipCaseError with the reason."""
    paragraphs = to_paragraphs(raw_html)
    item = golden["item"]
    phrases = list(golden["anchors"]["must_contain"])
    start, end = section_bounds(paragraphs, item, phrases)
    section = paragraphs[start:end]
    if len(section) < 2:
        raise SkipCaseError(f"item {item} section holds {len(section)} paragraphs")
    anchors = [_find_anchor(section, p) for p in phrases]
    kept = window_ids([a["offset"] for a in anchors], len(section), window)
    return {
        "accession": golden["accession"],
        "company": golden["company"],
        "form": golden["form"],
        "item": item,
        "filing_date": golden["filingDate"],
        "document_url": golden["documentUrl"],
        "golden_id": golden["id"],
        "window_paragraphs": window,
        "paragraphs": [{"id": i, "text": section[i]} for i in kept],
        "anchors": [
            {"phrase": a["phrase"], "paragraph_id": a["offset"], "sentence": a["sentence"]}
            for a in anchors
        ],
        # Not written to the fixture; the case writer reads it from here.
        "_cased": [a["cased_phrase"] for a in anchors],
    }


def case_yaml(fixture: dict[str, Any], index: int) -> tuple[str, str]:
    """The file name and text of one case: the `index`-th anchor of a
    fixture, asked as a question whose answer is checkable two ways."""
    name = f"{fixture['golden_id']}-a{index + 1}"
    phrase = fixture["anchors"][index]["phrase"]
    cased = fixture["_cased"][index]
    title = ITEM_TITLES.get(fixture["item"], "")
    goal = (
        f"Use the filing tools. In Item {fixture['item']} ({title}) of the {fixture['form']} "
        f"that {fixture['company']} filed on {fixture['filing_date']} (accession "
        f'{fixture["accession"]}), find the sentence containing the phrase "{phrase}". '
        "Reply with that sentence quoted verbatim inside double quotes, then one sentence "
        "in your own words saying what the passage is about."
    )
    wrapped = textwrap.fill(goal, width=94, initial_indent="  ", subsequent_indent="  ")
    body = (
        f"{CASE_HEADER}name: {name}\n"
        f"goal: >-\n{wrapped}\n"
        "max_steps: 6\n"
        "target_requirements: [agent]\n"
        "expect:\n"
        f"  answer_contains: {json.dumps(cased)}   # exact casing from the filing\n"
        "  grounded: true\n"
    )
    return f"{name}.yaml", body


def fetch(url: str, cache: Path, name: str, *, state: dict[str, float]) -> str:
    """The document at `url`, from `cache/name` when it is already there.

    A fetch waits REQUEST_SPACING_S after the previous one, sends the SEC's
    requested User-Agent, and retries a 403 or 429 after BACKOFF_S, up to
    MAX_ATTEMPTS times. Raises SkipCaseError when every attempt is refused or the
    transport fails, so one unreachable document skips its case instead of
    ending the build.
    """
    cached = cache / name
    if cached.exists():
        return cached.read_bytes().decode("utf-8", errors="replace")
    cache.mkdir(parents=True, exist_ok=True)
    last = "no attempt made"
    for attempt in range(1, MAX_ATTEMPTS + 1):
        wait = state.get("last_request", 0.0) + REQUEST_SPACING_S - time.monotonic()
        if wait > 0:
            time.sleep(wait)
        state["last_request"] = time.monotonic()
        try:
            response = httpx.get(
                url,
                headers={"User-Agent": USER_AGENT},
                timeout=REQUEST_TIMEOUT,
                follow_redirects=True,
            )
        except httpx.HTTPError as e:
            last = f"transport error: {e}"
        else:
            if response.status_code == 200:
                cached.write_bytes(response.content)
                return response.content.decode("utf-8", errors="replace")
            last = f"HTTP {response.status_code}"
            if response.status_code not in RATE_LIMIT_CODES:
                break
        if attempt < MAX_ATTEMPTS:
            print(f"    {last}; retrying in {BACKOFF_S:.0f}s", flush=True)
            time.sleep(BACKOFF_S)
    raise SkipCaseError(f"fetch failed ({last})")


def _golden_cases(golden_path: Path, only: str | None) -> list[dict[str, Any]]:
    """The golden cases that carry at least one anchor, narrowed by `--only`."""
    golden = json.loads(golden_path.read_text(encoding="utf-8"))
    cases = [c for c in golden["cases"] if c["anchors"]["must_contain"]]
    if only:
        cases = [c for c in cases if c["id"] == only]
        if not cases:
            raise SystemExit(f"no golden case with anchors is named {only!r}")
    return cases


def build(golden_path: Path, out: Path, cache: Path, *, window: int, only: str | None) -> int:
    """Write every buildable fixture and case under `out`; print the yield.

    Returns 0 when at least one case was written, 1 when none was, so a
    build that produced nothing fails a script runner.
    """
    cases = _golden_cases(golden_path, only)
    fixtures_dir = out / "fixtures"
    fixtures_dir.mkdir(parents=True, exist_ok=True)
    state: dict[str, float] = {}
    written, skipped = 0, []
    print(f"{len(cases)} golden cases carry anchors")
    for golden in cases:
        print(f"  {golden['id']}", flush=True)
        try:
            raw = fetch(
                golden["documentUrl"],
                cache,
                f"{golden['accession']}-{golden['primaryDocument']}",
                state=state,
            )
            fixture = build_fixture(golden, raw, window)
        except SkipCaseError as e:
            print(f"    skipped: {e}")
            skipped.append((golden["id"], str(e)))
            continue
        cased = fixture.pop("_cased")
        path = fixtures_dir / f"{fixture['accession']}-{fixture['item']}.json"
        path.write_text(json.dumps(fixture, indent=1, ensure_ascii=False), encoding="utf-8")
        fixture["_cased"] = cased
        for i in range(len(fixture["anchors"])):
            file_name, text = case_yaml(fixture, i)
            (out / file_name).write_text(text, encoding="utf-8")
            written += 1
        print(f"    {len(fixture['paragraphs'])} paragraphs, {len(cased)} cases")
    print(
        f"\nyield: {len(cases) - len(skipped)}/{len(cases)} filings, {written} cases, "
        f"{len(skipped)} filings skipped"
    )
    for case_id, reason in skipped:
        print(f"  skipped {case_id}: {reason}")
    return 0 if written else 1


def main(argv: list[str] | None = None) -> int:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--golden", type=Path, default=root / "suites/groundedness/golden.json")
    parser.add_argument("--out", type=Path, default=root / "suites/groundedness")
    parser.add_argument("--cache", type=Path, default=root / ".cache/edgar")
    parser.add_argument("--window", type=int, default=WINDOW_PARAGRAPHS)
    parser.add_argument("--only", default=None, help="build one golden case by its id")
    args = parser.parse_args(argv)
    return build(args.golden, args.out, args.cache, window=args.window, only=args.only)


if __name__ == "__main__":
    sys.exit(main())
